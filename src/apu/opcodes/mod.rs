pub fn execute_opcode(spc700: &mut Spc700, opcode: u8) {
    match opcode {
        // 0x00
        0x00 => nop(spc700),
        0x01 => tcall(spc700, 0),
        0x02 => set1(spc700, 0),
        0x03 => bbs(spc700, 0),
        0x04 => alu_a_dp(spc700, AluOp::Or),
        0x05 => alu_a_abs(spc700, AluOp::Or),
        0x06 => alu_a_ind_x(spc700, AluOp::Or),
        0x07 => alu_a_ind_dp_x(spc700, AluOp::Or),
        0x08 => alu_a_imm(spc700, AluOp::Or),
        0x09 => alu_dp_dp(spc700, AluOp::Or),
        0x0A => or1(spc700),
        0x0B => shift_dp(spc700, ShiftOp::Asl),
        0x0C => shift_abs(spc700, ShiftOp::Asl),
        0x0D => push_psw(spc700),
        0x0E => tset1(spc700),
        0x0F => brk(spc700),

        // 0x10
        0x10 => bpl_rel(spc700),
        0x11 => tcall(spc700, 1),
        0x12 => clr1(spc700, 0),
        0x13 => bbc(spc700, 0),
        0x14 => alu_a_dp_x(spc700, AluOp::Or),
        0x15 => alu_a_abs_x(spc700, AluOp::Or),
        0x16 => alu_a_abs_y(spc700, AluOp::Or),
        0x17 => alu_a_ind_dp_y(spc700, AluOp::Or),
        0x18 => alu_dp_imm(spc700, AluOp::Or),
        0x19 => alu_ind_x_ind_y(spc700, AluOp::Or),
        0x1A => decw(spc700),
        0x1B => shift_dp_x(spc700, ShiftOp::Asl),
        0x1C => shift_a(spc700, ShiftOp::Asl),
        0x1D => dec_x(spc700),
        0x1E => cmp_x_abs(spc700),
        0x1F => jmp_abs_x(spc700),

        // 0x20
        0x20 => clrp(spc700),
        0x21 => tcall(spc700, 2),
        0x22 => set1(spc700, 1),
        0x23 => bbs(spc700, 1),
        0x24 => alu_a_dp(spc700, AluOp::And),
        0x25 => alu_a_abs(spc700, AluOp::And),
        0x26 => alu_a_ind_x(spc700, AluOp::And),
        0x27 => alu_a_ind_dp_x(spc700, AluOp::And),
        0x28 => alu_a_imm(spc700, AluOp::And),
        0x29 => alu_dp_dp(spc700, AluOp::And),
        0x2A => or1_not(spc700),
        0x2B => shift_dp(spc700, ShiftOp::Rol),
        0x2C => shift_abs(spc700, ShiftOp::Rol),
        0x2D => push_a(spc700),
        0x2E => cbne_dp(spc700),
        0x2F => bra_rel(spc700),

        // 0x30
        0x30 => bmi_rel(spc700),
        0x31 => tcall(spc700, 3),
        0x32 => clr1(spc700, 1),
        0x33 => bbc(spc700, 1),
        0x34 => alu_a_dp_x(spc700, AluOp::And),
        0x35 => alu_a_abs_x(spc700, AluOp::And),
        0x36 => alu_a_abs_y(spc700, AluOp::And),
        0x37 => alu_a_ind_dp_y(spc700, AluOp::And),
        0x38 => alu_dp_imm(spc700, AluOp::And),
        0x39 => alu_ind_x_ind_y(spc700, AluOp::And),
        0x3A => incw(spc700),
        0x3B => shift_dp_x(spc700, ShiftOp::Rol),
        0x3C => shift_a(spc700, ShiftOp::Rol),
        0x3D => inc_x(spc700),
        0x3E => cmp_x_dp(spc700),
        0x3F => call_abs(spc700),

        // 0x40
        0x40 => setp(spc700),
        0x41 => tcall(spc700, 4),
        0x42 => set1(spc700, 2),
        0x43 => bbs(spc700, 2),
        0x44 => alu_a_dp(spc700, AluOp::Eor),
        0x45 => alu_a_abs(spc700, AluOp::Eor),
        0x46 => alu_a_ind_x(spc700, AluOp::Eor),
        0x47 => alu_a_ind_dp_x(spc700, AluOp::Eor),
        0x48 => alu_a_imm(spc700, AluOp::Eor),
        0x49 => alu_dp_dp(spc700, AluOp::Eor),
        0x4A => and1(spc700),
        0x4B => shift_dp(spc700, ShiftOp::Lsr),
        0x4C => shift_abs(spc700, ShiftOp::Lsr),
        0x4D => push_x(spc700),
        0x4E => tclr1(spc700),
        0x4F => pcall(spc700),

        // 0x50
        0x50 => bvc_rel(spc700),
        0x51 => tcall(spc700, 5),
        0x52 => clr1(spc700, 2),
        0x53 => bbc(spc700, 2),
        0x54 => alu_a_dp_x(spc700, AluOp::Eor),
        0x55 => alu_a_abs_x(spc700, AluOp::Eor),
        0x56 => alu_a_abs_y(spc700, AluOp::Eor),
        0x57 => alu_a_ind_dp_y(spc700, AluOp::Eor),
        0x58 => alu_dp_imm(spc700, AluOp::Eor),
        0x59 => alu_ind_x_ind_y(spc700, AluOp::Eor),
        0x5A => cmpw(spc700),
        0x5B => shift_dp_x(spc700, ShiftOp::Lsr),
        0x5C => shift_a(spc700, ShiftOp::Lsr),
        0x5D => mov_x_a(spc700),
        0x5E => cmp_y_abs(spc700),
        0x5F => jmp_abs(spc700),

        // 0x60
        0x60 => clrc(spc700),
        0x61 => tcall(spc700, 6),
        0x62 => set1(spc700, 3),
        0x63 => bbs(spc700, 3),
        0x64 => alu_a_dp(spc700, AluOp::Cmp),
        0x65 => alu_a_abs(spc700, AluOp::Cmp),
        0x66 => alu_a_ind_x(spc700, AluOp::Cmp),
        0x67 => alu_a_ind_dp_x(spc700, AluOp::Cmp),
        0x68 => alu_a_imm(spc700, AluOp::Cmp),
        0x69 => alu_dp_dp(spc700, AluOp::Cmp),
        0x6A => and1_not(spc700),
        0x6B => shift_dp(spc700, ShiftOp::Ror),
        0x6C => shift_abs(spc700, ShiftOp::Ror),
        0x6D => push_y(spc700),
        0x6E => dbnz_dp(spc700),
        0x6F => ret(spc700),

        // 0x70
        0x70 => bvs_rel(spc700),
        0x71 => tcall(spc700, 7),
        0x72 => clr1(spc700, 3),
        0x73 => bbc(spc700, 3),
        0x74 => alu_a_dp_x(spc700, AluOp::Cmp),
        0x75 => alu_a_abs_x(spc700, AluOp::Cmp),
        0x76 => alu_a_abs_y(spc700, AluOp::Cmp),
        0x77 => alu_a_ind_dp_y(spc700, AluOp::Cmp),
        0x78 => alu_dp_imm(spc700, AluOp::Cmp),
        0x79 => alu_ind_x_ind_y(spc700, AluOp::Cmp),
        0x7A => addw(spc700),
        0x7B => shift_dp_x(spc700, ShiftOp::Ror),
        0x7C => shift_a(spc700, ShiftOp::Ror),
        0x7D => mov_a_x(spc700),
        0x7E => cmp_y_dp(spc700),
        0x7F => ret1(spc700),

        // 0x80
        0x80 => setc(spc700),
        0x81 => tcall(spc700, 8),
        0x82 => set1(spc700, 4),
        0x83 => bbs(spc700, 4),
        0x84 => alu_a_dp(spc700, AluOp::Adc),
        0x85 => alu_a_abs(spc700, AluOp::Adc),
        0x86 => alu_a_ind_x(spc700, AluOp::Adc),
        0x87 => alu_a_ind_dp_x(spc700, AluOp::Adc),
        0x88 => alu_a_imm(spc700, AluOp::Adc),
        0x89 => alu_dp_dp(spc700, AluOp::Adc),
        0x8A => eor1(spc700),
        0x8B => dec_dp(spc700),
        0x8C => dec_abs(spc700),
        0x8D => mov_y_imm(spc700),
        0x8E => pop_psw(spc700),
        0x8F => mov_dp_imm(spc700),

        // 0x90
        0x90 => bcc_rel(spc700),
        0x91 => tcall(spc700, 9),
        0x92 => clr1(spc700, 4),
        0x93 => bbc(spc700, 4),
        0x94 => alu_a_dp_x(spc700, AluOp::Adc),
        0x95 => alu_a_abs_x(spc700, AluOp::Adc),
        0x96 => alu_a_abs_y(spc700, AluOp::Adc),
        0x97 => alu_a_ind_dp_y(spc700, AluOp::Adc),
        0x98 => alu_dp_imm(spc700, AluOp::Adc),
        0x99 => alu_ind_x_ind_y(spc700, AluOp::Adc),
        0x9A => subw(spc700),
        0x9B => dec_dp_x(spc700),
        0x9C => dec_a(spc700),
        0x9D => mov_x_sp(spc700),
        0x9E => div_ya_x(spc700),
        0x9F => xcn(spc700),

        // 0xA0
        0xA0 => ei(spc700),
        0xA1 => tcall(spc700, 10),
        0xA2 => set1(spc700, 5),
        0xA3 => bbs(spc700, 5),
        0xA4 => alu_a_dp(spc700, AluOp::Sbc),
        0xA5 => alu_a_abs(spc700, AluOp::Sbc),
        0xA6 => alu_a_ind_x(spc700, AluOp::Sbc),
        0xA7 => alu_a_ind_dp_x(spc700, AluOp::Sbc),
        0xA8 => alu_a_imm(spc700, AluOp::Sbc),
        0xA9 => alu_dp_dp(spc700, AluOp::Sbc),
        0xAA => mov1_c_mem(spc700),
        0xAB => inc_dp(spc700),
        0xAC => inc_abs(spc700),
        0xAD => cmp_y_imm(spc700),
        0xAE => pop_a(spc700),
        0xAF => mov_ind_x_inc_a(spc700),

        // 0xB0
        0xB0 => bcs_rel(spc700),
        0xB1 => tcall(spc700, 11),
        0xB2 => clr1(spc700, 5),
        0xB3 => bbc(spc700, 5),
        0xB4 => alu_a_dp_x(spc700, AluOp::Sbc),
        0xB5 => alu_a_abs_x(spc700, AluOp::Sbc),
        0xB6 => alu_a_abs_y(spc700, AluOp::Sbc),
        0xB7 => alu_a_ind_dp_y(spc700, AluOp::Sbc),
        0xB8 => alu_dp_imm(spc700, AluOp::Sbc),
        0xB9 => alu_ind_x_ind_y(spc700, AluOp::Sbc),
        0xBA => movw_ya_dp(spc700),
        0xBB => inc_dp_x(spc700),
        0xBC => inc_a(spc700),
        0xBD => mov_sp_x(spc700),
        0xBE => das(spc700),
        0xBF => mov_a_ind_x_inc(spc700),

        // 0xC0
        0xC0 => di(spc700),
        0xC1 => tcall(spc700, 12),
        0xC2 => set1(spc700, 6),
        0xC3 => bbs(spc700, 6),
        0xC4 => mov_dp_a(spc700),
        0xC5 => mov_abs_a(spc700),
        0xC6 => mov_ind_x_a(spc700),
        0xC7 => mov_ind_dp_x_a(spc700),
        0xC8 => cmp_x_imm(spc700),
        0xC9 => mov_abs_x(spc700),
        0xCA => mov1_mem_c(spc700),
        0xCB => mov_dp_y(spc700),
        0xCC => mov_abs_y(spc700),
        0xCD => mov_x_imm(spc700),
        0xCE => pop_x(spc700),
        0xCF => mul_ya(spc700),

        // 0xD0
        0xD0 => bne_rel(spc700),
        0xD1 => tcall(spc700, 13),
        0xD2 => clr1(spc700, 6),
        0xD3 => bbc(spc700, 6),
        0xD4 => mov_dp_x_a(spc700),
        0xD5 => mov_abs_x_a(spc700),
        0xD6 => mov_abs_y_a(spc700),
        0xD7 => mov_dp_y_a(spc700),
        0xD8 => mov_dp_x(spc700),
        0xD9 => mov_dp_y_x(spc700),
        0xDA => movw_dp_ya(spc700),
        0xDB => mov_dp_x_y(spc700),
        0xDC => dec_y(spc700),
        0xDD => mov_a_y(spc700),
        0xDE => cbne_dp_x(spc700),
        0xDF => daa(spc700),

        // 0xE0
        0xE0 => clrv(spc700),
        0xE1 => tcall(spc700, 14),
        0xE2 => set1(spc700, 7),
        0xE3 => bbs(spc700, 7),
        0xE4 => mov_a_dp(spc700),
        0xE5 => mov_a_abs(spc700),
        0xE6 => mov_a_ind_x(spc700),
        0xE7 => mov_a_ind_dp_x(spc700),
        0xE8 => mov_a_imm(spc700),
        0xE9 => mov_x_abs(spc700),
        0xEA => not1(spc700),
        0xEB => mov_y_dp(spc700),
        0xEC => mov_y_abs(spc700),
        0xED => notc(spc700),
        0xEE => pop_y(spc700),
        0xEF => sleep(spc700),

        // 0xF0
        0xF0 => beq_rel(spc700),
        0xF1 => tcall(spc700, 15),
        0xF2 => clr1(spc700, 7),
        0xF3 => bbc(spc700, 7),
        0xF4 => mov_a_dp_x(spc700),
        0xF5 => mov_a_abs_x(spc700),
        0xF6 => mov_a_abs_y(spc700),
        0xF7 => mov_a_ind_dp_y(spc700),
        0xF8 => mov_x_dp(spc700),
        0xF9 => mov_x_dp_y(spc700),
        0xFA => mov_dp_dp(spc700),
        0xFB => mov_y_dp_x(spc700),
        0xFC => inc_y(spc700),
        0xFD => mov_y_a(spc700),
        0xFE => dbnz_y(spc700),
        0xFF => stop(spc700),
    }
}
